/** SRT's local-binding switch permits wildcard inbound on macOS. Narrow that
 * generated grant before launch; never run a profile we cannot recognize. */
export function restrictLoopbackSandbox(argv: readonly string[], platform: NodeJS.Platform = process.platform): string[] {
  if (platform !== 'darwin') return [...argv]
  if (argv.length === 3 && argv[1] === '-c' && ['/bin/bash', '/bin/sh'].includes(argv[0] ?? '')) {
    const tokens = shellWords(argv[2]!)
    const narrowed = restrictLoopbackSandbox(tokens, platform)
    return [argv[0]!, '-c', narrowed.map(word => "'" + word.replaceAll("'", "'\\''") + "'").join(' ')]
  }
  const index = argv.indexOf('-p'), profile = argv[index + 1]
  if (index < 1 || argv[index - 1] !== '/usr/bin/sandbox-exec' || !profile) throw new Error('SANDBOX_LOOPBACK_PROFILE_UNRECOGNIZED')
  let changed = profile
  for (const operation of ['network-bind', 'network-inbound']) {
    const broad = `(allow ${operation} (local ip "*:*"))`
    if (!changed.includes(broad)) throw new Error('SANDBOX_LOOPBACK_PROFILE_UNRECOGNIZED')
    changed = changed.replaceAll(broad, `(allow ${operation} (local ip "localhost:*"))`)
  }
  return argv.map((arg, i) => i === index + 1 ? changed : arg)
}

/** Decode only a flat, quoted command generated by the trusted SRT wrapper.
 * Operators/expansions outside quotes fail closed; no shell is evaluated here. */
function shellWords(source: string): string[] {
  const words:string[]=[];let word='',quote='',started=false
  for(let i=0;i<source.length;i++) {
    const char=source[i]!
    if(char==='\\' && quote!=="'") {
      const next=source[++i]
      if(next===undefined)throw new Error('SANDBOX_LOOPBACK_PROFILE_UNRECOGNIZED')
      if(quote==='"' && !['$','`','"','\\','\n'].includes(next))word+='\\'
      if(next!=='\n')word+=next
      started=true;continue
    }
    if(quote) { if(char===quote)quote='';else word+=char;continue }
    if(char==="'"||char==='"'){quote=char;started=true;continue}
    if(/\s/.test(char)){if(started){words.push(word);word='';started=false}continue}
    if(/[;&|<>$`()]/.test(char))throw new Error('SANDBOX_LOOPBACK_PROFILE_UNRECOGNIZED')
    word+=char;started=true
  }
  if(quote)throw new Error('SANDBOX_LOOPBACK_PROFILE_UNRECOGNIZED')
  if(started)words.push(word)
  return words
}
