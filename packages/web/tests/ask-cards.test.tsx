import { cleanup, fireEvent, render, waitFor } from '@testing-library/react'
import { afterEach, beforeAll, expect, it, vi } from 'vitest'
import { InteractionPanel, type PendingInteraction } from '../src/InteractionPanel.js'

beforeAll(() => { vi.stubGlobal('ResizeObserver', class { observe() {} unobserve() {} disconnect() {} }); window.matchMedia = () => ({ matches: false, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} }) as unknown as MediaQueryList })
afterEach(() => { cleanup(); localStorage.clear() })
const question = (type = 'choice'): PendingInteraction => ({ kind: 'interaction', interactionKind: 'ask', runId: 'run-1', groupId: 'group-1', items: [{ effectId: 'q1', input: { type, prompt: '请审阅已保存的计划 docs/plans/feature.md，是否执行？', options: [{ label: '暂不执行', value: 'defer' }, { label: '执行', value: 'execute' }], min: 1 } }] })
it.each(['choice', 'multi'])('shows the %s custom answer below the choices without a disclosure', type => {
  const view = render(<InteractionPanel interaction={question(type)} reviewNote="" delegated={false} submit={async () => true}/>)
  expect(view.getByRole('textbox', { name: '自行回答' })).toBeTruthy()
  expect(view.queryByText('自行回答')).toBeNull()
  expect(view.getByPlaceholderText('输入你的答案…')).toBeTruthy()
  expect(view.container.querySelector('.question-custom details, details.question-custom, .question-custom summary')).toBeNull()
})
it('opens the exact legacy plan path without submitting an answer', () => {
  const open = vi.fn(), submit = vi.fn(async () => true)
  const view = render(<InteractionPanel interaction={question()} reviewNote="" delegated={false} onOpenFile={open} submit={submit}/>)
  fireEvent.click(view.getByRole('button', { name: 'docs/plans/feature.md' }))
  expect(open).toHaveBeenCalledWith('docs/plans/feature.md')
  expect(submit).not.toHaveBeenCalled()
})
it.each(['choice', 'multi', 'input'])('closes %s without submitting any draft answer', async type => {
  const submit = vi.fn(async () => true), interaction = question(type)
  interaction.items.push({ effectId: 'q2', input: { type: 'input', prompt: '补充说明' } })
  const view = render(<InteractionPanel interaction={interaction} reviewNote="" delegated={false} submit={submit}/>)
  fireEvent.change(view.getByRole('textbox'), { target: { value: 'unfinished draft' } })
  fireEvent.click(view.getByRole('button', { name: '不作答并关闭' }))
  await waitFor(() => expect(submit).toHaveBeenCalledWith([{ effectId: 'q1', value: { dismissed: true } }, { effectId: 'q2', value: { dismissed: true } }]))
  await waitFor(() => expect(view.queryByRole('button', { name: '不作答并关闭' })).toBeNull())
})
it('keeps a selected execution option when the plan note changes and refuses a typed approval phrase', async () => {
  const submit = vi.fn(async () => true)
  const view = render(<InteractionPanel interaction={question()} reviewNote="" delegated={false} submit={submit}/>)
  fireEvent.click(view.getByRole('button', { name: '执行' }))
  fireEvent.change(view.getByRole('textbox', { name: '自行回答' }), { target: { value: '同意执行' } })
  expect(view.getByRole('button', { name: '执行' }).getAttribute('aria-pressed')).toBe('true')
  fireEvent.click(view.getByRole('button', { name: '提交回答' }))
  await waitFor(() => expect(submit).toHaveBeenCalledWith([{ effectId: 'q1', value: { value: 'execute' } }]))
  view.unmount()
  const blocked = render(<InteractionPanel interaction={question()} reviewNote="" delegated={false} submit={submit}/>)
  fireEvent.change(blocked.getByRole('textbox', { name: '自行回答' }), { target: { value: '同意执行' } })
  expect(blocked.getByRole('button', { name: '提交回答' }).hasAttribute('disabled')).toBe(true)
  expect(blocked.getByText('请点选「执行」。输入这句话不能代替确认。')).toBeTruthy()
  expect(submit).toHaveBeenCalledTimes(1)
})
it('keeps the card and draft when closing fails, then allows retry', async () => {
  const submit = vi.fn().mockResolvedValueOnce(false).mockResolvedValueOnce(true)
  const view = render(<InteractionPanel interaction={question()} reviewNote="" delegated={false} submit={submit}/>)
  fireEvent.change(view.getByRole('textbox'), { target: { value: 'keep me' } })
  fireEvent.click(view.getByRole('button', { name: '不作答并关闭' }))
  await view.findByRole('alert')
  expect((view.getByRole('textbox') as HTMLTextAreaElement).value).toBe('keep me')
  fireEvent.click(view.getByRole('button', { name: '不作答并关闭' }))
  await waitFor(() => expect(submit).toHaveBeenCalledTimes(2))
})
