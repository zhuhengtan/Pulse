it('leaves a cleared key out of the save and sends null only after an explicit delete', async () => {
  const f = show({ enabled: true })
  const [asr, tts] = await screen.findAllByLabelText('API Key')
  fireEvent.change(asr!, { target: { value: 'typed-secret' } })
  fireEvent.change(asr!, { target: { value: '' } })
  fireEvent.change(tts!, { target: { value: '   ' } })
  fireEvent.change(within(screen.getByRole('region', { name: '语音识别服务' })).getByLabelText(/^模型/), { target: { value: '新识别模型' } })
  fireEvent.click(screen.getByRole('button', { name: '保存语音设置' }))
  await waitFor(() => expect(f.calls.filter(call => call.body)).toHaveLength(1))
  const body = f.calls.find(call => call.body)?.body
  expect(body).toMatchObject({ asr: { model: '新识别模型' } })
  expect(body).not.toHaveProperty('asrKey'); expect(body).not.toHaveProperty('ttsKey')
  fireEvent.click(screen.getAllByRole('button', { name: '删除已保存的 Key' })[0]!)
  expect(screen.getByRole('button', { name: '撤销删除密钥' })).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: '保存语音设置' }))
  await waitFor(() => expect(f.calls.filter(call => call.body)).toHaveLength(2))
  expect(f.calls.filter(call => call.body)[1]?.body).toMatchObject({ asrKey: null })
})

