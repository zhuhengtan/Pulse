import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeAll, expect, it, vi } from 'vitest'
import { PulseDesignSystem } from '../src/PulseDesignSystem.js'
import { VoiceSettings } from '../src/VoiceSettings.js'
import { voiceFixture } from './fixtures/voice.js'

beforeAll(() => {
  Object.defineProperty(window, 'matchMedia', { value: () => ({ matches: false, addEventListener() {}, removeEventListener() {} }), configurable: true })
  globalThis.ResizeObserver = class { observe() {}; unobserve() {}; disconnect() {} }
})
afterEach(() => { cleanup(); Reflect.deleteProperty(window, 'pulseDesktop'); vi.restoreAllMocks(); vi.unstubAllGlobals() })
function show(options: Parameters<typeof voiceFixture>[0] = {}, desktop = false) {
  if (desktop) Object.defineProperty(window, 'pulseDesktop', { value: {}, configurable: true })
  const fixture = voiceFixture({ enabled: true, ...options })
  const dirty = vi.fn()
  render(<PulseDesignSystem><VoiceSettings transport={fixture.transport} canManage onDirtyChange={dirty}/></PulseDesignSystem>)
  return { ...fixture, dirty }
}

async function wakeTab() {
  fireEvent.click(await screen.findByRole('tab', { name: '唤醒与声纹' }))
  return screen.findByLabelText('助手名字')
}
async function modelsTab() {
  fireEvent.click(screen.getByRole('tab', { name: '模型配置' }))
  return screen.findByRole('region', { name: '语音识别服务' })
}

it('persists the switch immediately, defaults to model downloads and hides both tabs when disabled', async () => {
  const f = show({ enabled: false }, true)
  const toggle = await screen.findByRole('switch', { name: '启用语音助手' })
  expect(toggle.getAttribute('aria-checked')).toBe('false')
  expect(screen.queryByRole('tab')).toBeNull()
  expect(screen.queryByRole('button', { name: '保存语音设置' })).toBeNull()
  fireEvent.click(toggle)
  const models = await screen.findByRole('tab', { name: '模型配置' })
  expect(models.getAttribute('aria-selected')).toBe('true')
  expect(screen.queryByLabelText('助手名字')).toBeNull()
  expect(screen.getByRole('button', { name: '下载唤醒与声纹模型' })).toBeTruthy()
  expect(screen.getByRole('button', { name: '一键安装识别模型' })).toBeTruthy()
  expect(screen.getByRole('button', { name: '一键安装播报模型' })).toBeTruthy()
  expect(f.calls.filter(call => call.body).map(call => call.path)).toEqual(['/api/voice/config', '/api/desktop/voice/resume'])
  fireEvent.change(await wakeTab(), { target: { value: 'x' } })
  await modelsTab()
  fireEvent.click(screen.getByRole('button', { name: '下载唤醒与声纹模型' }))
  await waitFor(() => expect(f.calls.some(call => call.path === '/api/desktop/voice/models')).toBe(true))
  expect(f.calls.filter(call => call.path === '/api/voice/config' && call.body)).toHaveLength(1)
  fireEvent.click(toggle)
  await waitFor(() => expect(screen.queryByRole('tab')).toBeNull())
  expect(toggle.getAttribute('aria-checked')).toBe('false')
  expect(screen.queryByRole('button', { name: '保存语音设置' })).toBeNull()
  expect(f.calls.filter(call => call.path === '/api/voice/config' && call.body)[1]?.body).toMatchObject({ enabled: false, name: 'Pulse' })
  expect(f.calls.some(call => call.path === '/api/desktop/voice/pause')).toBe(true)
})

